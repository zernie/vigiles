// @ts-check
/**
 * The CommonJS door of every public entry, for code that `require`s vigiles.
 *
 * vigiles is an ES module package. Each `exports` entry's `require` target is a
 * small CommonJS file that does one of two things:
 *
 * - **Node** (20.19+ / 22.12+) can `require` an ES module, so the door returns
 *   THE ES module itself. One copy of every module means one copy of every
 *   piece of module state — the eval-load guard (`core/eval-load-phase.ts`)
 *   that stops a paid call while an eval file loads must be the same flag for a
 *   `.eval.cjs` file as for the runner — and every module keeps its own
 *   `import.meta.dirname`, so helper programs beside it are found.
 * - **Jest** runs tests through its own loader, which cannot load an ES module
 *   at all; there the `require` throws a `SyntaxError`, and the door loads an
 *   esbuild bundle of the entry instead. Jest then loads everything through the
 *   bundle, so it too sees one copy. Inside the bundle each module's
 *   `import.meta` is rebuilt from that module's OWN original location, not the
 *   bundle's, so module-relative paths still point at the real files.
 *
 * Checked here, not trusted: under Node each door must return the identical ES
 * module; each bundle must expose the entry's export names; and every module
 * path a bundle bakes in must exist. Runs after `tsc` in `npm run build`.
 */
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { readFile } from "node:fs/promises";
import { createRequire } from "node:module";
import { dirname, relative, resolve, sep } from "node:path";
import { pathToFileURL } from "node:url";
import { build, transform } from "esbuild";

const pkg = JSON.parse(readFileSync("package.json", "utf8"));
const require = createRequire(import.meta.url);

/** @returns {{ name: string, esm: string, door: string, bundle: string }[]} */
const entries = () =>
  Object.entries(pkg.exports).flatMap(([name, target]) =>
    typeof target === "object" && typeof target.require === "string"
      ? [
          {
            name,
            esm: target.import,
            door: target.require,
            bundle: target.require.replace(/\.cjs$/, ".bundle.cjs"),
          },
        ]
      : [],
  );

/**
 * The path from `from`'s directory to `to`, as `require` reads it: POSIX
 * separators, and `./` in front of a sibling, which would otherwise read as a
 * package name.
 *
 * @param {string} from
 * @param {string} to
 */
const rel = (from, to) => {
  const p = relative(dirname(from), to).split(sep).join("/");
  return p.startsWith("../") ? p : `./${p}`;
};

/**
 * The door: the ES module under Node, the bundle where `require` cannot load
 * an ES module (Jest).
 *
 * @param {{ esm: string, door: string, bundle: string }} e
 */
const door = (e) => `"use strict";
// Generated by scripts/build-cjs.mjs. Node returns the ES module itself (one
// instance, its own paths); Jest cannot load ES modules and gets the bundle.
try {
  module.exports = require(${JSON.stringify(rel(e.door, e.esm))});
} catch (error) {
  if (!(error instanceof SyntaxError)) throw error;
  module.exports = require(${JSON.stringify(rel(e.door, e.bundle))});
}
`;

/**
 * Rebuilds `import.meta` inside a bundled module from where THAT module lives,
 * relative to the bundle file at run time. `define` replaces only expressions,
 * never text inside a string.
 *
 * @param {string} outfile
 * @returns {import("esbuild").Plugin}
 */
const moduleRelativeMeta = (outfile) => ({
  name: "module-relative-import-meta",
  setup(b) {
    b.onLoad({ filter: /\.js$/ }, async (args) => {
      const text = await readFile(args.path, "utf8");
      if (!text.includes("import.meta")) return undefined;
      const { code } = await transform(text, {
        loader: "js",
        format: "esm",
        define: {
          "import.meta.url": "__vmUrl",
          "import.meta.dirname": "__vmDir",
          "import.meta.filename": "__vmFile",
        },
      });
      const prelude =
        'import { join as __vmJoin, dirname as __vmDirname } from "node:path";\n' +
        'import { pathToFileURL as __vmToUrl } from "node:url";\n' +
        `const __vmFile = __vmJoin(__dirname, ${JSON.stringify(rel(outfile, args.path))});\n` +
        "const __vmDir = __vmDirname(__vmFile);\n" +
        "const __vmUrl = __vmToUrl(__vmFile).href;\n";
      return { contents: prelude + code, loader: "js" };
    });
  },
});

/** @param {{ esm: string, bundle: string }} e */
const bundle = (e) =>
  build({
    entryPoints: [e.esm],
    outfile: e.bundle,
    bundle: true,
    platform: "node",
    format: "cjs",
    target: "node20",
    packages: "external",
    plugins: [moduleRelativeMeta(e.bundle)],
    logLevel: "warning",
  });

// Entries that load only inside their test runner: `vigiles/jest` imports
// `@jest/globals`, which Jest provides. `npm run test:jest` checks it instead,
// by loading it as a user's Jest setup does.
const RUNNER_ONLY = new Set(["./jest"]);

/** @param {string} p */
const fromHere = (p) => `./${p.replace(/^\.\//, "../")}`;

/** @param {{ name: string, esm: string, door: string, bundle: string }} e */
const problemsOf = async (e) => {
  const baked = [
    ...readFileSync(e.bundle, "utf8").matchAll(
      // In the CommonJS output the prelude reads
      // `__vmFile3 = (0, import_node_path4.join)(__dirname, "../../core/x.js")`:
      // esbuild suffixes names where modules collide and rewrites the import.
      /__vmFile\d* = [^;]*?\(__dirname, "([^"]+)"\)/g,
    ),
  ]
    .map((m) => resolve(dirname(e.bundle), m[1] ?? ""))
    .filter((p) => !existsSync(p))
    .map((p) => `${e.name}: the bundle points at ${p}, which does not exist`);
  if (RUNNER_ONLY.has(e.name)) return baked;
  const esm = await import(pathToFileURL(e.esm).href);
  const same =
    require(fromHere(e.door)) === esm
      ? []
      : [`${e.name}: under Node the CommonJS door is not the ES module itself`];
  const names = Object.keys(require(fromHere(e.bundle)));
  const missing = Object.keys(esm).filter((k) => !names.includes(k));
  const lacking = missing.length
    ? [`${e.name}: the bundle lacks ${missing.join(", ")}`]
    : [];
  return [...baked, ...same, ...lacking];
};

const list = entries();
await Promise.all(list.map(bundle));
for (const e of list) writeFileSync(e.door, door(e));
// Not vacuous: the main entry's graph reads `import.meta` (sandbox, egress),
// so its bundle must carry baked module paths for the check above to judge.
const mainBundle = list.find((e) => e.name === ".")?.bundle ?? "";
const bakedInMain = /__vmFile\d* = [^;]*?\(__dirname, "/.test(
  readFileSync(mainBundle, "utf8"),
);
const problems = [
  ...(bakedInMain
    ? []
    : [
        ". : the bundle carries no module path, so the path check judged nothing",
      ]),
  ...(await Promise.all(list.map(problemsOf))).flat(),
];
if (problems.length > 0) {
  for (const p of problems) console.error(`✗ build-cjs: ${p}`);
  process.exit(1);
}
console.log(
  `✓ build-cjs: ${String(list.length)} CommonJS doors — the ES module itself under Node, a checked bundle under Jest`,
);
